# shellcheck shell=bash
# render_config — prints a headscale config that talks to nothing outside your server:
# own DERP relay only (no Tailscale DERP map), no update checks, no log uploads.
#
# Inputs (environment):
#   HOST         public IP or DNS name clients use to reach the server   (required)
#   PORT         HTTPS port                                              (default 443)
#   TLS_MODE     own-ca | letsencrypt                                    (default own-ca)
#   ACME_EMAIL   contact for Let's Encrypt                               (letsencrypt only)
#   PUBLIC_IP    public IPv4 advertised for the relay                    (default: HOST if it is an IP)
#   BASE_DOMAIN  MagicDNS suffix, e.g. laptop.fastnet.internal           (default fastnet.internal)
#   TLS_DIR      where server.crt/server.key live                        (default /etc/headscale/tls)
#   STATE_DIR    headscale data                                          (default /var/lib/headscale)
#   RUN_DIR      unix socket directory                                   (default /var/run/headscale)
render_config() {
  : "${HOST:?HOST is required}"
  local port=${PORT:-443} mode=${TLS_MODE:-own-ca} state=${STATE_DIR:-/var/lib/headscale}
  local tls=${TLS_DIR:-/etc/headscale/tls} run=${RUN_DIR:-/var/run/headscale}
  local url="https://$HOST" ip=${PUBLIC_IP:-}
  [ "$port" = 443 ] || url="$url:$port"
  [ -z "$ip" ] && is_ipv4 "$HOST" && ip=$HOST

  cat <<EOF
# Generated by fastnet ($(date -u +%Y-%m-%dT%H:%M:%SZ)). Re-run server/install.sh to change it.
server_url: $url
listen_addr: 0.0.0.0:$port
metrics_listen_addr: 127.0.0.1:9090
grpc_listen_addr: 127.0.0.1:50443
grpc_allow_insecure: false

noise:
  private_key_path: $state/noise_private.key

prefixes:
  v4: 100.64.0.0/10
  v6: fd7a:115c:a1e0::/48
  allocation: sequential

derp:
  server:
    enabled: true
    region_id: 999
    region_code: "fastnet"
    region_name: "fastnet self-hosted relay"
    verify_clients: true
    stun_listen_addr: "0.0.0.0:3478"
    private_key_path: $state/derp_server_private.key
    automatically_add_embedded_derp_region: true
EOF
  [ -n "$ip" ] && echo "    ipv4: $ip"
  cat <<EOF
  # No Tailscale relays: clients only ever use the relay on this server.
  urls: []
  paths: []
  auto_update_enabled: false
  update_frequency: 24h

disable_check_updates: true

node:
  expiry: 0

database:
  type: sqlite
  sqlite:
    path: $state/db.sqlite
    write_ahead_log: true

EOF
  if [ "$mode" = letsencrypt ]; then
    cat <<EOF
acme_url: https://acme-v02.api.letsencrypt.org/directory
acme_email: "${ACME_EMAIL:-}"
tls_letsencrypt_hostname: "$HOST"
tls_letsencrypt_cache_dir: $state/cache
tls_letsencrypt_challenge_type: HTTP-01
tls_letsencrypt_listen: ":http"
tls_cert_path: ""
tls_key_path: ""
EOF
  else
    cat <<EOF
tls_letsencrypt_hostname: ""
tls_cert_path: $tls/server.crt
tls_key_path: $tls/server.key
EOF
  fi
  cat <<EOF

log:
  level: info
  format: text

policy:
  mode: file
  path: ""

dns:
  magic_dns: true
  base_domain: ${BASE_DOMAIN:-fastnet.internal}
  override_local_dns: false
  nameservers:
    global: []
    split: {}
  search_domains: []
  extra_records: []

unix_socket: $run/headscale.sock
unix_socket_permission: "0770"

logtail:
  enabled: false

taildrop:
  enabled: true
EOF
}
